-- 実機ライブで発覚した不具合の修正：
-- 「お題ボードの右下の分母(例:7/9)が回答者と審査員で違う」「採点したのに
-- 相手の画面ではボールが降ってこない」「満点じゃないのに金色になる」。
--
-- ScoringPhysicsBoardの分母(maxBalls)は「審査資格のある参加者数×3」で、
-- これまで各クライアントが自分のparticipants一覧から毎回その場で
-- (eligibleJudgeCount = 自分の組以外のplayer数)を計算していた。ターン開始の
-- 瞬間に参加者の入退室・組再編とタイミングが重なると、クライアントごとに
-- 参加者一覧のRealtime反映タイミングがずれ、同じターンなのに「自分の組以外の
-- player数」の計算結果がクライアントごとに異なってしまうことがあった
-- （ScoringPhysicsBoard側は1回答の審査サイクル中この値を固定して使うため、
-- 一度ずれるとそのサイクル中ずっとクライアント間で食い違ったまま進む）。
--
-- 「ゲームを開始する」時点で全ターンをまとめて作成しており、以降プレイヤーの
-- 組分け自体は変わらない設計のため、各ターンの審査資格者数はturns作成時に
-- 1回だけサーバー側で確定させ、列として持たせる。全クライアントが同じ
-- turns行を読むため、これで全員が必ず同じ分母を見るようになる。

alter table public.turns add column eligible_judge_count int not null default 0;
